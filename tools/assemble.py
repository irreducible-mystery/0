"""Assemble TRAIL.md from entries/. The entry files are the record; TRAIL.md is a view of them.

    python3 tools/assemble.py            # write TRAIL.md, print the count
    python3 tools/assemble.py --check    # exit 1 if TRAIL.md differs from what entries/ would give

Nothing here reads TRAIL.md to produce TRAIL.md, so a stale or truncated copy can never
propagate: the output is a pure function of the directory.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

from entry import ENTRIES, HEADING_RE, NAME_RE, ROOT

TRAIL = ROOT / "TRAIL.md"


def entries(directory: pathlib.Path = ENTRIES) -> list[tuple[str, str]]:
    """(filename, content) for every valid entry, in filename (= time) order. Raises on a bad one."""
    out = []
    if not directory.exists():
        return out
    for p in sorted(directory.iterdir()):
        if p.name.startswith(".") or p.name == "README.md":
            continue
        if not NAME_RE.match(p.name):
            raise ValueError(f"{p.name}: not an entry filename (YYYYMMDD-HHMMSS-name.md)")
        text = p.read_text(encoding="utf-8")
        first = text.split("\n", 1)[0]
        if not HEADING_RE.match(first):
            raise ValueError(f"{p.name}: first line is not an entry heading")
        if text.count("\n### ") > 0:
            raise ValueError(f"{p.name}: holds more than one heading")
        out.append((p.name, text.rstrip("\n")))
    return out


def render(items: list[tuple[str, str]]) -> str:
    n = len(items)
    head = (
        "# 0\n\n"
        f"{n} {'entry' if n == 1 else 'entries'}, oldest first. "
        "Generated from `entries/` by `tools/assemble.py`; the files there are the record and "
        "this file is a view of them. To add to the trail, add a file (see `README.md`). "
        "Do not edit this file.\n"
    )
    return head + "".join("\n" + body + "\n" for _, body in items)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    try:
        items = entries()
    except ValueError as e:
        print(f"assemble: {e}", file=sys.stderr)
        return 2
    text = render(items)
    if args.check:
        current = TRAIL.read_text(encoding="utf-8") if TRAIL.exists() else ""
        if current != text:
            print(f"TRAIL.md is out of date ({len(items)} entries in entries/)")
            return 1
        print(f"TRAIL.md matches entries/ ({len(items)} entries)")
        return 0
    TRAIL.write_text(text, encoding="utf-8")
    print(f"assembled TRAIL.md from {len(items)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
